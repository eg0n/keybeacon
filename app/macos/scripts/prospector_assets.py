"""Generate the Prospector screens' assets from a prospector-zmk-module checkout.

Writes CrystalFrames.swift (the crystal animation) and ProspectorFonts.swift (the LVGL bitmap
fonts the screens draw with, plus the icon code points) into Sources/BleWidgetScreens. LVGL's
sources come from a Zephyr workspace (zephyr/module.yml's modules/lib/gui/lvgl):

    python3 scripts/prospector_assets.py ~/src/zmk-modules/prospector-zmk-module path/to/lvgl
"""

import argparse
import base64
import re
import struct
import zlib
from pathlib import Path

ADAPTER = Path("boards/shields/prospector_adapter")
OUTPUT = Path(__file__).resolve().parent.parent / "Sources/BleWidgetScreens"

# (where, font file) -> (Swift property, code points to keep or None for all). "module" fonts are
# in the adapter's src/fonts, "lvgl" ones in LVGL's src/font.
FONTS = {
    ("module", "PixelOperatorMono32"): ("pixelOperatorMono32", None),
    ("module", "material_32"): ("material32", None),
    ("module", "FR_Regular_48"): ("fracRegular48", None),
    ("module", "FR_Thin_48"): ("fracThin48", None),
    ("module", "FR_Regular_36"): ("fracRegular36", None),
    ("module", "FR_Regular_30"): ("fracRegular30", None),
    ("module", "FR_Medium_32"): ("fracMedium32", None),
    ("module", "FG_Medium_20"): ("gridnikMedium20", None),
    ("module", "FG_Medium_24"): ("gridnikMedium24", None),
    ("module", "FG_Medium_26"): ("gridnikMedium26", None),
    ("module", "DINish_Medium_24"): ("dinishMedium24", None),
    ("module", "DINish_Expanded_Light_36"): ("dinishExpandedLight36", None),
    ("module", "PPF_NarrowThin_64"): ("ppfNarrowThin64", None),
    ("module", "Symbols_Bold_26"): ("symbolsBold26", None),
    ("module", "Symbols_Regular_28"): ("symbolsRegular28", None),
    ("module", "Symbols_Semibold_28"): ("symbolsSemibold28", None),
    ("module", "Symbols_Semibold_32"): ("symbolsSemibold32", None),
    # LV_SYMBOL_CLOSE, in the default font, for Classic's offline halves.
    ("lvgl", "lv_font_montserrat_20"): ("montserrat20", {0xF00D}),
}

HEADER = """// swift-format-ignore-file
// Copyright (c) 2026 The TOTEM ZMK Contributors / KeyBeacon Contributors
// SPDX-License-Identifier: MIT

// Generated by scripts/prospector_assets.py from prospector-zmk-module and LVGL; do not edit.
"""


def c_bytes(text):
    return bytes(int(h, 16) for h in re.findall(r"0x([0-9a-fA-F]{1,2})\b", text))


def crystal_frames(module):
    source = (module / ADAPTER / "src/layouts/crystal/crystal.c").read_text()
    frames = []
    for match in re.finditer(r"crystal_\d\d_map\[\] = \{(.*?)\};", source, re.S):
        data = c_bytes(match.group(1).split("#endif", 1)[1])
        assert len(data) == 69 * 9, len(data)
        frames.append(base64.b64encode(data).decode())
    assert len(frames) == 16
    lines = [
        HEADER,
        "/// The 16 frames of the crystal animation (layouts/crystal/crystal.c), 68×69 at 1 bit per",
        "/// pixel, 9 bytes per row, most significant bit first.",
        "enum CrystalFrames {",
        "    static let width = 68",
        "    static let height = 69",
        "    static let stride = 9",
        "    static let base64 = [",
        *[f'        "{frame}",' for frame in frames],
        "    ]",
        "}",
        "",
    ]
    (OUTPUT / "CrystalFrames.swift").write_text("\n".join(lines))


def field(source, name):
    match = re.search(rf"\.{name}\s*=\s*(-?\d+)", source)
    assert match, name
    return int(match.group(1))


def packed(data):
    """Raw DEFLATE, then base64: what Data.decompressed(using: .zlib) reads back."""
    deflate = zlib.compressobj(9, zlib.DEFLATED, -15)
    return base64.b64encode(deflate.compress(data) + deflate.flush()).decode()


def parse_font(path, keep=None):
    """An lv_font_fmt_txt font (uncompressed bitmaps) as packed glyph, bitmap and kerning tables.

    `keep` limits it to those code points. Kerning comes out per code point pair, in 1/16 px.
    """
    source = path.read_text()
    assert field(source, "bitmap_format") == 0, path
    bpp = field(source, "bpp")
    bitmap = c_bytes(re.search(r"glyph_bitmap\[\] = \{(.*?)\};", source, re.S).group(1))
    descriptors = [
        tuple(int(v) for v in m)
        for m in re.findall(
            r"\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), \.box_h = (\d+), "
            r"\.ofs_x = (-?\d+), \.ofs_y = (-?\d+)",
            source,
        )
    ]
    lists = {
        name: [int(v, 0) for v in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", body)]
        for name, body in re.findall(
            r"static const u?int\d+_t (\w+)\[\] =\s*\{(.*?)\};", source, re.S
        )
    }

    glyphs = {}
    cmaps = re.search(r"cmaps\[\] =\s*\{(.*?)\n\};", source, re.S).group(1)
    for cmap in re.findall(r"\{(.*?)\}", cmaps, re.S):
        start = field(cmap, "range_start")
        first = field(cmap, "glyph_id_start")
        kind = re.search(r"\.type = (\w+)", cmap).group(1)
        unicode_list = re.search(r"\.unicode_list = (\w+)", cmap).group(1)
        offsets = re.search(r"\.glyph_id_ofs_list = (\w+)", cmap).group(1)
        if kind.startswith("LV_FONT_FMT_TXT_CMAP_FORMAT0"):
            deltas = range(field(cmap, "range_length"))
        else:
            deltas = lists[unicode_list]
        for i, delta in enumerate(deltas):
            glyphs[start + delta] = first + (
                lists[offsets][i] if offsets != "NULL" else i
            )
    if keep is not None:
        glyphs = {cp: g for cp, g in glyphs.items() if cp in keep}

    # Kerning by glyph id, as LVGL looks it up: pairs, or a left x right class table.
    kern = {}
    scale = field(source, "kern_scale")
    if re.search(r"\.kern_dsc = &kern_pairs", source):
        ids = lists["kern_pair_glyph_ids"]
        for i, value in enumerate(lists["kern_pair_values"]):
            kern[(ids[2 * i], ids[2 * i + 1])] = value
    elif re.search(r"\.kern_dsc = &kern_classes", source):
        left = lists["kern_left_class_mapping"]
        right = lists["kern_right_class_mapping"]
        values = lists["kern_class_values"]
        rights = field(source, "right_class_cnt")
        for lg in glyphs.values():
            for rg in glyphs.values():
                if left[lg] > 0 and right[rg] > 0:
                    kern[(lg, rg)] = values[(left[lg] - 1) * rights + right[rg] - 1]
    by_glyph = {g: cp for cp, g in glyphs.items()}
    kerning = b"".join(
        struct.pack("<IIh", by_glyph[lg], by_glyph[rg], (value * scale) >> 4)
        for (lg, rg), value in sorted(kern.items())
        if value and lg in by_glyph and rg in by_glyph
    )

    # Repack the kept glyphs' bitmaps back to back.
    table, pixels = b"", b""
    for cp, g in sorted(glyphs.items()):
        index, adv_w, width, height, ofs_x, ofs_y = descriptors[g]
        size = (width * height * bpp + 7) // 8
        table += struct.pack("<7i", cp, len(pixels), adv_w, width, height, ofs_x, ofs_y)
        pixels += bitmap[index : index + size]
    return {
        "bpp": bpp,
        "line_height": field(source, "line_height"),
        "base_line": field(source, "base_line"),
        "bitmap": packed(pixels),
        "glyphs": packed(table),
        "kerning": packed(kerning) if kerning else "",
    }


def code_points(header):
    """`#define NAME "<UTF-8>"` lines as (camelCase name, code point)."""
    for name, escaped in re.findall(
        r'#define (\w+) "((?:\\x[0-9a-fA-F]{2})+)"', header.read_text()
    ):
        char = bytes(
            int(h, 16) for h in re.findall(r"\\x([0-9a-fA-F]{2})", escaped)
        ).decode()
        name = name.removeprefix("SYMBOL_")
        camel = re.sub(r"_(\w)", lambda m: m.group(1).upper(), name.lower())
        yield camel, ord(char)


def fonts(module, lvgl):
    lines = [HEADER, "extension LVGLFont {"]
    for (source, file), (prop, keep) in FONTS.items():
        root = (
            module / ADAPTER / "src/fonts" if source == "module" else lvgl / "src/font"
        )
        font = parse_font(root / f"{file}.c", keep)
        lines += [
            f"    /// {file}.c",
            f"    static let {prop} = LVGLFont(",
            f"        bpp: {font['bpp']}, lineHeight: {font['line_height']}, baseLine: {font['base_line']},",
            f'        bitmap: "{font["bitmap"]}",',
            f'        glyphs: "{font["glyphs"]}",',
            f'        kerning: "{font["kerning"]}")',
            "",
        ]
    lines[-1] = "}"
    for header, enum, doc in [
        ("material_32.h", "MaterialIcon", "Material Symbols in material_32"),
        ("symbols.h", "ProspectorSymbol", "SF Symbols in the Symbols_* fonts"),
    ]:
        lines += [
            "",
            f"/// Code points of the {doc} (include/{header}).",
            f"enum {enum} {{",
        ]
        lines += [
            f'    static let {name} = "\\u{{{point:04X}}}"'
            for name, point in code_points(module / ADAPTER / "include" / header)
        ]
        lines += ["}"]
    lines += [""]
    (OUTPUT / "ProspectorFonts.swift").write_text("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("module", type=Path, help="a prospector-zmk-module checkout")
    parser.add_argument("lvgl", type=Path, help="LVGL 9 sources (modules/lib/gui/lvgl)")
    args = parser.parse_args()
    crystal_frames(args.module.expanduser())
    fonts(args.module.expanduser(), args.lvgl.expanduser())


if __name__ == "__main__":
    main()
