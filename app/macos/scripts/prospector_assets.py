"""Generate the Prospector screens' assets from a prospector-zmk-module checkout.

Writes CrystalFrames.swift (the crystal animation) and ProspectorFonts.swift (the LVGL bitmap
fonts the screens draw with, plus the Material icon code points) into Sources/BleWidgetScreens:

    python3 scripts/prospector_assets.py ~/src/zmk-modules/prospector-zmk-module
"""

import argparse
import base64
import re
import struct
from pathlib import Path

ADAPTER = Path("boards/shields/prospector_adapter")
OUTPUT = Path(__file__).resolve().parent.parent / "Sources/BleWidgetScreens"

# LVGL font file (src/fonts/<name>.c) -> Swift property name.
FONTS = {
    "PixelOperatorMono32": "pixelOperatorMono32",
    "material_32": "material32",
}

HEADER = """// swift-format-ignore-file
// Copyright (c) 2026 The TOTEM ZMK Contributors / KeyBeacon Contributors
// SPDX-License-Identifier: MIT

// Generated by scripts/prospector_assets.py from prospector-zmk-module; do not edit.
"""


def c_bytes(text):
    return bytes(int(h, 16) for h in re.findall(r"0x([0-9a-fA-F]{1,2})\b", text))


def crystal_frames(module):
    source = (module / ADAPTER / "src/layouts/crystal/crystal.c").read_text()
    frames = []
    for match in re.finditer(r"crystal_\d\d_map\[\] = \{(.*?)\};", source, re.S):
        data = c_bytes(match.group(1).split("#endif", 1)[1])
        assert len(data) == 69 * 9, len(data)
        frames.append(base64.b64encode(data).decode())
    assert len(frames) == 16
    lines = [
        HEADER,
        "/// The 16 frames of the crystal animation (layouts/crystal/crystal.c), 68×69 at 1 bit per",
        "/// pixel, 9 bytes per row, most significant bit first.",
        "enum CrystalFrames {",
        "    static let width = 68",
        "    static let height = 69",
        "    static let stride = 9",
        "    static let base64 = [",
        *[f'        "{frame}",' for frame in frames],
        "    ]",
        "}",
        "",
    ]
    (OUTPUT / "CrystalFrames.swift").write_text("\n".join(lines))


def field(source, name):
    match = re.search(rf"\.{name}\s*=\s*(-?\d+)", source)
    assert match, name
    return int(match.group(1))


def parse_font(path):
    """Code point -> glyph descriptor, for an lv_font_fmt_txt font without compression or kerning."""
    source = path.read_text()
    assert field(source, "bitmap_format") == 0, path
    bitmap = c_bytes(re.search(r"glyph_bitmap\[\] = \{(.*?)\};", source, re.S).group(1))
    descriptors = [
        tuple(int(v) for v in m)
        for m in re.findall(
            r"\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), \.box_h = (\d+), "
            r"\.ofs_x = (-?\d+), \.ofs_y = (-?\d+)",
            source,
        )
    ]
    lists = {
        name: [int(v, 0) for v in re.findall(r"0x[0-9a-fA-F]+|\d+", body)]
        for name, body in re.findall(
            r"static const uint\d+_t (\w+)\[\] = \{(.*?)\};", source, re.S
        )
    }
    glyphs = {}
    cmaps = re.search(r"cmaps\[\] =\s*\{(.*?)\n\};", source, re.S).group(1)
    for cmap in re.findall(r"\{(.*?)\}", cmaps, re.S):
        start = field(cmap, "range_start")
        length = field(cmap, "range_length")
        first = field(cmap, "glyph_id_start")
        kind = re.search(r"\.type = (\w+)", cmap).group(1)
        unicode_list = re.search(r"\.unicode_list = (\w+)", cmap).group(1)
        offsets = re.search(r"\.glyph_id_ofs_list = (\w+)", cmap).group(1)
        if kind.startswith("LV_FONT_FMT_TXT_CMAP_FORMAT0"):
            for i in range(length):
                glyph = first + (lists[offsets][i] if offsets != "NULL" else i)
                glyphs[start + i] = glyph
        else:
            for i, delta in enumerate(lists[unicode_list]):
                glyph = first + (lists[offsets][i] if offsets != "NULL" else i)
                glyphs[start + delta] = glyph
    table = b"".join(
        struct.pack("<7i", cp, *descriptors[g]) for cp, g in sorted(glyphs.items())
    )
    return {
        "bpp": field(source, "bpp"),
        "line_height": field(source, "line_height"),
        "base_line": field(source, "base_line"),
        "bitmap": base64.b64encode(bitmap).decode(),
        "glyphs": base64.b64encode(table).decode(),
    }


def material_icons(module):
    header = (module / ADAPTER / "include/material_32.h").read_text()
    icons = []
    for name, escaped in re.findall(
        r'#define (\w+) "((?:\\x[0-9a-fA-F]{2})+)"', header
    ):
        char = bytes(
            int(h, 16) for h in re.findall(r"\\x([0-9a-fA-F]{2})", escaped)
        ).decode()
        camel = re.sub(r"_(\w)", lambda m: m.group(1).upper(), name.lower())
        icons.append(f'    static let {camel} = "\\u{{{ord(char):04X}}}"')
    return icons


def fonts(module):
    lines = [HEADER, "extension LVGLFont {"]
    for file, prop in FONTS.items():
        font = parse_font(module / ADAPTER / "src/fonts" / f"{file}.c")
        lines += [
            f"    /// src/fonts/{file}.c",
            f"    static let {prop} = LVGLFont(",
            f"        bpp: {font['bpp']}, lineHeight: {font['line_height']}, baseLine: {font['base_line']},",
            f'        bitmap: "{font["bitmap"]}",',
            f'        glyphs: "{font["glyphs"]}")',
            "",
        ]
    lines[-1] = "}"
    lines += [
        "",
        "/// Code points of the Material Symbols in material_32 (include/material_32.h).",
        "enum MaterialIcon {",
    ]
    lines += material_icons(module)
    lines += ["}", ""]
    (OUTPUT / "ProspectorFonts.swift").write_text("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("module", type=Path, help="a prospector-zmk-module checkout")
    module = parser.parse_args().module.expanduser()
    crystal_frames(module)
    fonts(module)


if __name__ == "__main__":
    main()
